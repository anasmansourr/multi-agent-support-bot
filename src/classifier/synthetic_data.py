# ------------------------------------------------------------------ builders
def build_synthetic(seed=config.SEED, variants_per_core=4):
    rng = random.Random(seed)
    rows = []
    for intent, cores in CORES.items():
        for idx, core in enumerate(cores):
            forms = [
                core,
                rng.choice(PREFIXES) + core,
                core + rng.choice(SUFFIXES),
                rng.choice(PREFIXES) + core + rng.choice(SUFFIXES),
            ][:variants_per_core]
            for text in dict.fromkeys(forms):               # de-duplicate, keep order
                rows.append({"text": text, "label": intent, "source": "synthetic",
                             "original_label": "hand_written", "group": f"{intent}_{idx}"})
    return pd.DataFrame(rows)


