# ------------------------------------------------------------------ builders
def build_synthetic(seed=config.SEED, variants_per_core=4):
    rng = random.Random(seed)
    rows = []
    for intent, cores in CORES.items():
        for idx, core in enumerate(cores):
            forms = [
                core,
                rng.choice(PREFIXES) + core,
                core + rng.choice(SUFFIXES),
                rng.choice(PREFIXES) + core + rng.choice(SUFFIXES),
            ][:variants_per_core]
            for text in dict.fromkeys(forms):               # de-duplicate, keep order
                rows.append({"text": text, "label": intent, "source": "synthetic",
                             "original_label": "hand_written", "group": f"{intent}_{idx}"})
    return pd.DataFrame(rows)


def build_hard_test():
    rows = [{"text": t, "label": lab, "source": "hard_test", "original_label": "hand_written",
             "group": f"hard_{i}", "note": note} for i, (t, lab, note) in enumerate(HARD_TEST)]
    return pd.DataFrame(rows)


def main():
    config.SYNTHETIC_DIR.mkdir(parents=True, exist_ok=True)
    synth, hard = build_synthetic(), build_hard_test()
    synth.to_csv(config.SYNTHETIC_DIR / "synthetic.csv", index=False)
    hard.to_csv(config.SYNTHETIC_DIR / "hard_test.csv", index=False)
    print("SYNTHETIC rows per intent:\n", synth["label"].value_counts().to_string())
    print("\nCore sentences (groups) per intent:\n", synth.groupby("label")["group"].nunique().to_string())
    print("\nHARD TEST rows per intent:\n", hard["label"].value_counts().to_string())
    print("\nSaved ->", config.SYNTHETIC_DIR)


if __name__ == "__main__":
    main()
